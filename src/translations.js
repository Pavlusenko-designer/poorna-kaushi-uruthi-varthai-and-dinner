export function getInitialLanguage() {
  const requested = new URL(location.href).searchParams.get("lang");
  if (Object.hasOwn(translations, requested)) return requested;
  try {
    const saved = localStorage.getItem("invitation-language");
    if (Object.hasOwn(translations, saved)) return saved;
  } catch {
    /* Storage may be disabled in a messenger webview. */
  }
  return "en";
}
